/** The viewer's pick: "auto" (follow the machine), or one of the dictionaries. Both of these are
    reassigned by app.js. */
let langPref = "auto";
try {
  langPref = localStorage.getItem("cm-lang") || "auto";
} catch { /* storage blocked: follow the machine */ }
let machineLang = null;

/** The language in effect: the pick, else the machine's, else the browser's, else English. */
function lang() {
  if (langPref !== "auto" && I18N[langPref]) return langPref;
  if (machineLang && I18N[machineLang]) return machineLang;
  const nav = (navigator.language || "").slice(0, 2);
  return I18N[nav] ? nav : "en";
}

function t(key, vars = {}) {
  const s = I18N[lang()][key] ?? I18N.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Fill the static markup: data-i18n (text), data-i18n-html (trusted dictionary markup),
    data-i18n-ph (placeholder), data-i18n-title (title and aria-label). */
function applyI18n(root = document) {
  document.documentElement.lang = lang();
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll("[data-i18n-title]")) {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  }
}
